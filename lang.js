window.LANG = window.LANG || "mr";
window.LANG_LIST = [
  { code: "mr", label: "मराठी" },
  { code: "hi", label: "हिन्दी" },
  { code: "en", label: "English" }
];

window.t = function (key, vars) {
  const dict = window.LANGS[window.LANG] || window.LANGS.mr;
  let s = dict[key];
  if (s === undefined) s = (window.LANGS.hi[key] !== undefined ? window.LANGS.hi[key] : key);
  if (vars) Object.keys(vars).forEach(v => { s = s.split("{" + v + "}").join(vars[v]); });
  return s;
};

/* HTML me data-i18n / data-i18n-ph / data-i18n-title attributes apply karo */
window.applyLang = function () {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.innerHTML = window.t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    el.placeholder = window.t(el.getAttribute("data-i18n-ph"));
  });
  document.querySelectorAll("[data-i18n-title]").forEach(el => {
    el.title = window.t(el.getAttribute("data-i18n-title"));
  });
  document.querySelectorAll("option[data-i18n]").forEach(el => {
    el.textContent = window.t(el.getAttribute("data-i18n"));
  });
  document.documentElement.lang = window.LANG;
};